/**
 * Build-time blog gate for Local Cascade.
 *
 * Posts live in content/blog/*.md. A post is eligible only when its `date`
 * is on or before the America/New_York calendar date of the build. The
 * client bundle, sitemap, RSS feed, copied images, and prerendered HTML
 * are produced from that eligible set. Scheduled posts stay in git and
 * out of every public artifact until a later build.
 */
import fs from "node:fs";
import path from "node:path";

export const ORIGIN = "https://www.localcascade.com";
export const PUBLISH_TIMEZONE = "America/New_York";

export const BLOG_HEADING = "Notes for law firms";
export const BLOG_DESCRIPTION =
  "Notes from Local Cascade on websites for US law firms: how a site reads, how people find it, and how a visit becomes a conversation.";
export const BLOG_KEYWORDS =
  "law firm website, attorney website, law firm web design";

const FIELDS = new Set([
  "title",
  "description",
  "date",
  "slug",
  "author",
  "cover",
  "coverAlt",
]);
const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const IMAGE_EXT_RE = /\.(?:jpe?g|png|webp|gif|svg)$/i;
const BANNED = [
  { re: /\$/, label: "a dollar sign" },
  { re: /\b\d[\d,]*\s+dollars?\b/i, label: "a dollar amount" },
  { re: /\bUSD\b/, label: "a dollar amount" },
  { re: /\bexperts?\b/i, label: 'the word "expert"' },
  {
    re: /\bspeciali(?:sts?|z(?:e|es|ed|ing|ation)|s(?:e|es|ed|ing|ation))\b/i,
    label: 'the word "specialist" or "specialize"',
  },
  { re: /\bguarante(?:e|ed|es|eing)\b/i, label: 'the word "guarantee"' },
  { re: /\btestimonials?\b/i, label: 'the word "testimonial"' },
  { re: /\bour clients\b/i, label: 'the phrase "our clients"' },
];

export function calendarDate(instant, timeZone = PUBLISH_TIMEZONE) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(instant);
  const get = type => parts.find(part => part.type === type)?.value;
  const year = get("year");
  const month = get("month");
  const day = get("day");
  if (!year || !month || !day) {
    throw new Error(`could not format a calendar date in ${timeZone}`);
  }
  return `${year}-${month}-${day}`;
}

export function unpublishedPreviewEnabled(command, env = process.env) {
  return (
    command === "serve" &&
    env.BLOG_PREVIEW_UNPUBLISHED === "1" &&
    env.VERCEL_ENV !== "production"
  );
}

export function loadPosts(root) {
  const dir = path.join(root, "content", "blog");
  if (!fs.existsSync(dir)) return [];
  const files = fs
    .readdirSync(dir)
    .filter(name => name.endsWith(".md"))
    .sort();
  const posts = [];
  const errors = [];
  for (const file of files) {
    try {
      posts.push(readPost(dir, file));
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      for (const line of message.split("\n")) {
        if (line.trim()) errors.push(line);
      }
    }
  }
  const seen = new Set();
  for (const post of posts) {
    if (seen.has(post.slug))
      errors.push(`${post.file}: duplicate slug ${post.slug}`);
    seen.add(post.slug);
  }
  if (errors.length) {
    throw new Error(
      `blog: invalid posts\n${errors.map(item => `- ${item}`).join("\n")}`
    );
  }
  return posts;
}

export function snapshot(root, now = new Date(), options = {}) {
  const includeUnpublished = options.includeUnpublished === true;
  const asOfDate = calendarDate(now);
  const all = loadPosts(root);
  const internal = all
    .filter(post => includeUnpublished || post.date <= asOfDate)
    .sort(
      (a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug)
    );
  const posts = internal.map(toClientPost);
  return {
    builtAt: now.toISOString(),
    asOfDate,
    includeUnpublished,
    posts,
    index: toIndex(posts),
    internal,
  };
}

export function publishedSnapshot(root, now = new Date()) {
  return snapshot(root, now, { includeUnpublished: false });
}

export function countScheduled(root, now = new Date()) {
  const asOfDate = calendarDate(now);
  return loadPosts(root).filter(post => post.date > asOfDate).length;
}

